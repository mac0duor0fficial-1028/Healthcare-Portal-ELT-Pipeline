-- One-time bootstrap. Run as ACCOUNTADMIN (or SECURITYADMIN + SYSADMIN split).
-- Before running: generate two key pairs and paste the PUBLIC keys below
--   openssl genrsa 2048 | openssl pkcs8 -topk8 -inform PEM -out loader_key.p8 -nocrypt
--   openssl rsa -in loader_key.p8 -pubout -out loader_key.pub     (strip BEGIN/END lines + newlines)
USE ROLE ACCOUNTADMIN;

-- Compute -----------------------------------------------------------------
CREATE WAREHOUSE IF NOT EXISTS WH_ELT
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- Databases ---------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS TELEHEALTH_RAW;
CREATE DATABASE IF NOT EXISTS TELEHEALTH_ANALYTICS;
CREATE SCHEMA   IF NOT EXISTS TELEHEALTH_RAW.API;

-- Roles -------------------------------------------------------------------
CREATE ROLE IF NOT EXISTS LOADER;
CREATE ROLE IF NOT EXISTS TRANSFORMER;
GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE WH_ELT TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE WH_ELT TO ROLE TRANSFORMER;

GRANT USAGE ON DATABASE TELEHEALTH_RAW TO ROLE LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA TELEHEALTH_RAW.API TO ROLE LOADER;

GRANT USAGE ON DATABASE TELEHEALTH_RAW TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA TELEHEALTH_RAW.API TO ROLE TRANSFORMER;
GRANT SELECT ON ALL    TABLES IN SCHEMA TELEHEALTH_RAW.API TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TELEHEALTH_RAW.API TO ROLE TRANSFORMER;

GRANT ALL ON DATABASE TELEHEALTH_ANALYTICS TO ROLE TRANSFORMER;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE TELEHEALTH_ANALYTICS TO ROLE TRANSFORMER;

-- Raw tables (append-only, one VARIANT per source record) -------------------
USE ROLE LOADER;
USE WAREHOUSE WH_ELT;
USE SCHEMA TELEHEALTH_RAW.API;

CREATE STAGE IF NOT EXISTS STG_RAW_JSON FILE_FORMAT = (TYPE = JSON);

CREATE TABLE IF NOT EXISTS RAW_ROLES                    (payload VARIANT, _batch_id STRING, _loaded_at TIMESTAMP_TZ, _source_endpoint STRING);
CREATE TABLE IF NOT EXISTS RAW_USERS                    (payload VARIANT, _batch_id STRING, _loaded_at TIMESTAMP_TZ, _source_endpoint STRING);
CREATE TABLE IF NOT EXISTS RAW_LOCATIONS                (payload VARIANT, _batch_id STRING, _loaded_at TIMESTAMP_TZ, _source_endpoint STRING);
CREATE TABLE IF NOT EXISTS RAW_DISEASES                 (payload VARIANT, _batch_id STRING, _loaded_at TIMESTAMP_TZ, _source_endpoint STRING);
CREATE TABLE IF NOT EXISTS RAW_VISITING_HOURS_SCHEDULES (payload VARIANT, _batch_id STRING, _loaded_at TIMESTAMP_TZ, _source_endpoint STRING);
CREATE TABLE IF NOT EXISTS RAW_PATIENTS                 (payload VARIANT, _batch_id STRING, _loaded_at TIMESTAMP_TZ, _source_endpoint STRING);
CREATE TABLE IF NOT EXISTS RAW_APPOINTMENTS             (payload VARIANT, _batch_id STRING, _loaded_at TIMESTAMP_TZ, _source_endpoint STRING);

CREATE TABLE IF NOT EXISTS EXTRACT_LOG (
  batch_id STRING, endpoint STRING, row_count NUMBER, status STRING, message STRING,
  loaded_at TIMESTAMP_TZ
);

-- Re-grant so TRANSFORMER sees tables created just now
USE ROLE ACCOUNTADMIN;
GRANT SELECT ON ALL TABLES IN SCHEMA TELEHEALTH_RAW.API TO ROLE TRANSFORMER;

-- Service users (key-pair auth). TYPE=SERVICE needs a recent account; delete it on older ones.
CREATE USER IF NOT EXISTS SVC_LOADER
  TYPE = SERVICE DEFAULT_ROLE = LOADER DEFAULT_WAREHOUSE = WH_ELT
  RSA_PUBLIC_KEY = '<PASTE_LOADER_PUBLIC_KEY>';
CREATE USER IF NOT EXISTS SVC_DBT
  TYPE = SERVICE DEFAULT_ROLE = TRANSFORMER DEFAULT_WAREHOUSE = WH_ELT
  RSA_PUBLIC_KEY = '<PASTE_DBT_PUBLIC_KEY>';
GRANT ROLE LOADER      TO USER SVC_LOADER;
GRANT ROLE TRANSFORMER TO USER SVC_DBT;
ALTER USER SVC_LOADER SET TIMEZONE = 'UTC';
ALTER USER SVC_DBT    SET TIMEZONE = 'UTC';

